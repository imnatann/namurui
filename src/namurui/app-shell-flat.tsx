"use client";

import { useEffect, useRef, useState, type ReactNode } from "react";

/*
 * App Shell Flat – the app frame with the sidebar laid straight on the page.
 * The sidebar sits on the tray colour, the page runs edge to edge, and a single hairline
 * separates them. The workspace and the account open small menus, the guide card sits at
 * the foot of the sidebar, and under 760px the sidebar slides over the page as a drawer.
 * The page body is whatever you pass as children; without children it shows the
 * "your page goes here" placeholder from the reference.
 */

export type FlatShellNavItem = {
  /** Text shown in the sidebar and passed to onNavigate */
  label: string;
  /** Leading glyph; the grid mark is drawn when omitted */
  icon?: ReactNode;
};

export type ShellNews = {
  /** Small line above the title, in the accent colour */
  kicker: string;
  /** Headline of the announcement */
  title: string;
  /** Footer action under the card */
  action: string;
  /** Depth of the stacked cards; 1 removes the card behind (the CSS keys off it) */
  count?: number;
  /** Called when the footer action is clicked */
  onAction?: () => void;
};

export type ShellGuide = {
  /** Title of the progress card */
  title: string;
  /** How far along the onboarding is, in percent */
  percent: number;
  /** Accent-coloured encouragement next to the percentage */
  cheer?: string;
  /** Called when the card is clicked; the checklist itself lives outside the shell */
  onOpen?: () => void;
};

export type AppShellFlatProps = {
  /** The page shown to the right of the sidebar; without it the placeholder page renders */
  children?: ReactNode;
  /** Label of the menu item or project that is open */
  active?: string;
  /** Called with the label of a menu item or project when it is clicked */
  onNavigate?: (label: string) => void;
  /** Workspace name; its first letter becomes the logo */
  workspace?: string;
  /** Workspaces offered by the switcher */
  workspaces?: string[];
  /** Account at the bottom; without an avatar it shows initials */
  user?: { name: string; avatar?: string };
  /** Menu items of the top group, each { label, icon } */
  nav?: FlatShellNavItem[];
  /** Project labels under the Projects heading */
  projects?: string[];
  /**
   * Page heading. Omitted: "Overview" when the shell has no children, no heading when it has.
   * Pass null to leave it out either way.
   */
  pageTitle?: string | null;
  /** Page standfirst, derived the same way as pageTitle */
  pageSub?: string | null;
  /** Placeholder shown instead of children; null removes it */
  empty?: { title: string; text: string } | null;
  /** The announcement card above the guide; null removes it */
  news?: ShellNews | null;
  /** The onboarding progress card; null removes it */
  guide?: ShellGuide | null;
  /** Called when the search button in the sidebar header is clicked */
  onSearch?: () => void;
  /** Extra class on the root */
  className?: string;
};

